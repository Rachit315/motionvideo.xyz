// Writes audio/cues.json from src/launch/timeline.ts, so every sound sits on a frame the
// picture computes. Run: node --experimental-strip-types audio/write-cues.ts
import { writeFileSync } from "node:fs";
import { BAR, CUES, DROP, DURATION, FPS, MUSIC, START } from "../src/launch/timeline.ts";

const cues = {
  _doc: "Generated by audio/write-cues.ts from src/launch/timeline.ts; do not edit by hand.",
  fps: FPS,
  bpm: MUSIC.bpm,
  total: DURATION,
  acts: {
    problem: { from: 0, dur: DROP },
    reveal: { from: DROP, dur: START.gallery - DROP },
    product: { from: START.gallery, dur: START.directory - START.gallery },
    proof: { from: START.directory, dur: START.lockup - START.directory },
    lockup: { from: START.lockup, dur: DURATION - START.lockup },
  },
  cue: Object.fromEntries(CUES.map((c) => [c.id, Math.round(c.f * 100) / 100])),
  events: CUES.map((c) => ({ ...c, f: Math.round(c.f * 100) / 100 })),
};
writeFileSync(new URL("./cues.json", import.meta.url), `${JSON.stringify(cues, null, 1)}\n`);

const s = (f: number) => (f / FPS).toFixed(4);
console.log(`total ${DURATION} frames (${s(DURATION)} s); drop at ${DROP} (${s(DROP)} s); bar ${BAR.toFixed(3)} frames`);
console.log(`starts: ${Object.entries(START).map(([k, v]) => `${k} ${v}`).join(", ")}`);
const cut = START.lockup + 99;
console.log(`lockup cut ${cut} (${s(cut)} s) = drop + ${((cut - DROP) / BAR).toFixed(3)} bars`);
console.log(`music: src ${(MUSIC.srcDrop - DROP / FPS).toFixed(4)} at film 0; cut bar line src ${(MUSIC.srcDrop + (cut - DROP) / FPS).toFixed(4)}`);
